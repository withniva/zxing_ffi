    def qr(name, payload, transform: nil, **expect)
      encoder = "rqrcode_core #{RQRCodeCore::VERSION} byte mode, EC level M, #{QR_MODULE_PX} px modules, " \
                "#{QR_QUIET_ZONE}-module quiet zone"
      encoder += ", #{TRANSFORMS.fetch(transform)}" if transform
      render = -> { apply(transform, *qr_raster(payload)) }
      @fixtures << Fixture.new(name:, encoder:, transform:, render:, expect:)
    end

    def zint(name, type, data, options, transform: nil, **expect)
      args = ["-b", type, *COMMON, *options, "-d", data]
      encoder = (["zint"] + args).map { |arg| shell_word(arg) }.join(" ")
      encoder += " (#{TRANSFORMS.fetch(transform)})" if transform
      render = -> { apply(transform, *zint_raster(args)) }
      @fixtures << Fixture.new(name:, encoder:, transform:, render:, expect:)
    end

    # QR Code structured append: one symbol per file. The ID is the QR parity byte (XOR of all message bytes), which
    # zxing-cpp reports as the decimal sequence id.
    def structured_append(prefix, parts)
      parity = parts.join.bytes.reduce(0, :^)
      parts.each_with_index do |part, index|
        zint "#{prefix}_#{index + 1}", "QRCODE", part, [*QR_ZINT, "--structapp=#{index + 1},#{parts.size},#{parity}"],
          format: "qr_code", text: part,
          sequence: {"index" => index, "size" => parts.size, "id" => parity.to_s},
          notes: "symbol #{index + 1} of #{parts.size}; the complete message is #{parts.join.inspect}"
      end
    end

    # --- rendering ----------------------------------------------------------------------------------------------

    def build(fixture)
      width, height, pixels = fixture.render.call
      validate!(fixture, width, height, pixels)
      File.binwrite(pgm_path(fixture.name), "P5\n#{width} #{height}\n255\n".b + pixels)
      entry(fixture)
    end

    # Module matrix -> 8-bit pixels, drawn directly (no zxing-cpp, no image library involved).
    def qr_raster(payload)
      modules = RQRCodeCore::QRCode.new(payload, level: :m, mode: :byte_8bit).modules
      size = (modules.size + 2 * QR_QUIET_ZONE) * QR_MODULE_PX
      margin = WHITE.chr * (QR_QUIET_ZONE * QR_MODULE_PX)
      quiet_rows = [WHITE.chr * size] * (QR_QUIET_ZONE * QR_MODULE_PX)
      rows = modules.flat_map do |row|
        line = margin + row.map { |dark| (dark ? BLACK : WHITE).chr * QR_MODULE_PX }.join + margin
        [line] * QR_MODULE_PX
      end
      [size, size, (quiet_rows + rows + quiet_rows).join]
    end

    def zint_raster(args)
      png = run!("zint", "--direct", "--filetype=PNG", *args)
      pgm = run!("magick", "png:-", "-colorspace", "Gray", "-depth", "8", "-strip", "pgm:-", stdin_data: png)
      header = pgm.match(/\AP5\s+(\d+)\s+(\d+)\s+255\s/n) or raise "unexpected magick output for #{args.inspect}"
      width, height = header.captures.map(&:to_i)
      [width, height, pgm.byteslice(header.end(0)..)]
    end

    def apply(transform, width, height, pixels)
      case transform
      when nil then [width, height, pixels]
      when :invert then [width, height, pixels.bytes.map { |v| WHITE - v }.pack("C*")]
      when :mirror then [width, height, rows(width, height, pixels).map(&:reverse).join]
      when :align_addon then align_addon(width, height, pixels)
      when :margin then margin(width, height, pixels)
      end
    end

    def margin(width, height, pixels)
      padded = width + 2 * MARGIN_PX
      side = WHITE.chr * MARGIN_PX
      quiet_rows = [WHITE.chr * padded] * MARGIN_PX
      lines = rows(width, height, pixels).map { |line| side + line + side }
      [padded, height + 2 * MARGIN_PX, (quiet_rows + lines + quiet_rows).join]
    end

    # zint draws EAN/UPC add-on bars lower than the main bars (it reserves room for the add-on text even with
    # --notext), so scan lines near the top cross the main symbol only and zxing-cpp would report it a second time
    # without the add-on. Drop those rows so that every scan line crosses both parts.
    def align_addon(width, height, pixels)
      lines = rows(width, height, pixels)
      last_bar = lines.filter_map { |line| line.rindex(BLACK.chr) }.max # right edge of the add-on
      first_black = lines.index { |line| line.include?(BLACK.chr) }
      addon_top = lines.index { |line| line.getbyte(last_bar) == BLACK }
      kept = lines[0...first_black] + lines[addon_top..]
      [width, kept.size, kept.join]
    end

    def rows(width, height, pixels)
      Array.new(height) { |y| pixels.byteslice(y * width, width) }
    end

    # Clean fixture: exact size, only black/white pixels, uniform background along all four edges.
    def validate!(fixture, width, height, pixels)
      name = fixture.name
      raise "#{name}: expected #{width * height} pixels, got #{pixels.bytesize}" unless pixels.bytesize == width * height
      raise "#{name}: not a bilevel image" unless pixels.delete(BILEVEL).empty?

      background = (fixture.transform == :invert) ? BLACK : WHITE
      lines = rows(width, height, pixels)
      edges = lines.first.bytes + lines.last.bytes + lines.flat_map { |line| [line.getbyte(0), line.getbyte(-1)] }
      raise "#{name}: quiet zone is not clean" unless edges.all?(background)
    end

    # --- index.yml ----------------------------------------------------------------------------------------------

    def entry(fixture)
      expect = fixture.expect
      format = expect.fetch(:format)
      bytes = (expect[:bytes] == true) ? expect.fetch(:text) : expect[:bytes]
      {
        "file" => "symbologies/#{fixture.name}.pgm",
        "format" => format,
        "symbology" => FAMILY.fetch(format),
        "text" => expect.fetch(:text),
        "bytes_hex" => bytes&.b&.unpack1("H*"),
        "content_type" => expect.fetch(:content_type, "text"),
        "encoder" => fixture.encoder,
        "read_options" => expect[:read_options],
        "sequence" => expect[:sequence],
        "notes" => expect.fetch(:notes, "")
      }.compact
    end

    def write_index(entries)
      encoders = "zint #{zint_version}, rqrcode_core #{RQRCodeCore::VERSION}"
      body = entries.map do |entry|
        entry.map.with_index { |(key, value), i| "#{i.zero? ? "- " : "  "}#{key}: #{yaml_value(value)}\n" }.join
      end
      yaml = format(HEADER, encoders:) + "\n" + body.join("\n")
      loaded = YAML.safe_load(yaml)
      raise "index.yml does not round-trip" unless loaded == entries

      File.write(INDEX, yaml)
    end

    PLAIN = /\A[a-z][a-z0-9_.\/]*\z/
    YAML_WORDS = %w[y n yes no on off true false null].freeze

    def yaml_value(value)
      case value
      when Hash then "{#{value.map { |k, v| "#{k}: #{yaml_value(v)}" }.join(", ")}}"
      when String then (value.match?(PLAIN) && !YAML_WORDS.include?(value)) ? value : yaml_quote(value)
      else value.to_s
      end
    end

    # YAML double-quoted scalar; control characters (C0, DEL, C1) as \xHH, everything else verbatim UTF-8.
    def yaml_quote(string)
      escaped = string.each_char.map do |char|
        code = char.ord
        if char == "\\" || char == "\""
          "\\#{char}"
        elsif code < 0x20 || (0x7F..0x9F).cover?(code)
          format("\\x%02X", code)
        else
          char
        end
      end
      "\"#{escaped.join}\""
    end

    # --- helpers ------------------------------------------------------------------------------------------------

    def check_tools!
      version = zint_version
      unless version && Gem::Version.new(version) >= MIN_ZINT
        abort "symbologies: zint >= #{MIN_ZINT} is required (found #{version || "none"}); e.g. `brew install zint`"
      end
      magick = run!("magick", "-version")
      abort "symbologies: ImageMagick 7 (`magick`) is required" unless magick.include?("ImageMagick 7")
    end

    def zint_version
      @zint_version ||= run!("zint", "--version")[/Zint version (\d+(?:\.\d+)+)/, 1]
    end

    # Runs a command (no shell) and returns its binary stdout; any failure or stderr output (zint prints warnings
    # there with exit status 0) aborts the generator.
    def run!(*argv, stdin_data: nil)
      out, err, status = Open3.capture3(*argv, stdin_data: stdin_data.to_s, binmode: true)
      return out if status.success? && err.empty?

      abort "symbologies: `#{argv.map { |a| shell_word(a) }.join(" ")}` failed: #{err.strip}"
    rescue Errno::ENOENT
      abort "symbologies: `#{argv.first}` not found on PATH (need zint >= #{MIN_ZINT} and ImageMagick 7)"
    end

    def shell_word(arg)
      arg.match?(%r{\A[\w.,:=/+@%-]+\z}) ? arg : "'#{arg.gsub("'", "'\\\\''")}'"
    end

    def remove_stale_files
      wanted = @fixtures.map { |f| pgm_path(f.name) }
      (Dir[File.join(OUT_DIR, "*.pgm")] - wanted).each { |path| File.delete(path) }
    end

    def pgm_path(name)
      File.join(OUT_DIR, "#{name}.pgm")
    end

    def relative(path)
      path.delete_prefix("#{ROOT}/")
    end
  end
end

