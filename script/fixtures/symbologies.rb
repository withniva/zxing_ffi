#!/usr/bin/env ruby
# frozen_string_literal: true

# Generates the symbology fixtures for the native tests: one clean 8-bit binary PGM (P5, maxval 255,
# black on white, generous quiet zone, 3-4 px modules, no rotation) per readable symbology/variant in
# test/fixtures/symbologies/, plus test/fixtures/symbologies/index.yml with the expected results (schema:
# test/fixtures/README.md). These are not corpus fixtures, so no manifest.d fragment is written.
#
#   mise exec -- bundle exec ruby script/fixtures/symbologies.rb
#   mise exec -- bundle exec script/generate_fixtures symbologies
#
# Encoders are independent of zxing-cpp so the tests are not circular: zint (>= 2.16) for most symbologies and
# the rqrcode gem for QR Code. zint's PNG output is converted to grayscale with ImageMagick 7 (`magick`). The output is
# deterministic: re-running with the same tool versions produces identical bytes.

